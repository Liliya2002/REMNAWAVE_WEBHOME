-- В базу знаний попадают ВСЕ диалоги, а не только прошедшие отбор.
--
-- Раньше пара, не прошедшая фильтр, просто выбрасывалась: из 71 найденной в
-- истории в базу попали 17, а остальные 54 исчезли без следа — их нельзя было
-- ни посмотреть, ни оценить, ни включить вручную. Решение за человека принимал
-- регэксп, и молча.
--
-- Теперь сохраняются все, но не прошедшие отбор приходят выключенными и с
-- причиной. Ассистент их не видит (в подбор идут только активные), а человек
-- видит, разбирает и включает нужные одним нажатием.
ALTER TABLE ai_knowledge
  ADD COLUMN IF NOT EXISTS skip_reason TEXT,
  -- Человек трогал эту строку руками. Автоматическая перепроверка фильтрами
  -- такие не переключает: иначе включённый админом пример на следующем прогоне
  -- сборщика выключался бы обратно, и так по кругу.
  ADD COLUMN IF NOT EXISTS reviewed_by_admin BOOLEAN NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS idx_ai_knowledge_skipped
  ON ai_knowledge (account_id, is_active, skip_reason);
