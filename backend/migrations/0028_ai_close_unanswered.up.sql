-- Закрывать старые тикеты и тогда, когда клиент остался без ответа.
--
-- Осознанное решение владельца проекта: на этой базе «заброшенных» тикетов
-- (где ответили мы, а клиент замолчал) не оказалось вовсе — все 34 открытых
-- старых тикета висят без ответа с нашей стороны. Разбирать их руками никто
-- не будет, поэтому закрываем по давности.
--
-- Тикеты про возврат средств продолжают исключаться независимо от возраста —
-- отдельное стоящее правило, здесь оно не отменяется.
ALTER TABLE ai_assistant_settings
  ADD COLUMN IF NOT EXISTS close_stale_unanswered BOOLEAN DEFAULT true;

-- Прежний текст прощания винил клиента в молчании. Теперь закрываем и тех,
-- кому не ответили мы, — формулировка должна быть нейтральной.
-- Меняем только у тех, кто не правил текст под себя.
UPDATE ai_assistant_settings
   SET close_stale_message = 'Закрываем обращение из-за давности. Если вопрос ещё актуален — напишите нам снова, разберёмся.'
 WHERE close_stale_message = 'Закрываем обращение из-за долгого отсутствия ответа. Если вопрос ещё актуален — напишите нам снова, мы продолжим с этого места.';

ALTER TABLE ai_assistant_settings
  ALTER COLUMN close_stale_message
  SET DEFAULT 'Закрываем обращение из-за давности. Если вопрос ещё актуален — напишите нам снова, разберёмся.';
