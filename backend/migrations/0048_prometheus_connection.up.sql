-- PROMETHEUS: собственное подключение к нейросети.
--
-- Раньше он брал подключение у ассистента тикетов — одно на всех. Это неудобно
-- и опасно сразу с двух сторон. Ассистент отвечает живым клиентам, и перевод
-- его на непроверенного провайдера ради одного разбора — не та цена. А
-- требования у них разные: ассистенту нужна дешёвая и быстрая модель на
-- короткий ответ, PROMETHEUS живёт вызовом инструментов и без них бесполезен.
--
-- Пустые поля означают «как у ассистента»: настраивать отдельно нужно только
-- то, что действительно отличается.
CREATE TABLE IF NOT EXISTS prometheus_settings (
  id            SERIAL PRIMARY KEY,
  api_key       TEXT,                  -- ВСЕГДА через encrypt(), наружу только has_key
  base_url      VARCHAR(512),
  model         VARCHAR(128),
  max_tokens    INTEGER,

  -- Не всякий шлюз понимает управление размышлением: часть отбивает такой
  -- запрос четырёхсотой ошибкой. Признак выставляет проверка связи, а не
  -- человек — угадывать это руками бессмысленно.
  send_thinking BOOLEAN NOT NULL DEFAULT true,

  -- Итог последней проверки связи: дошёл ли запрос, отвечает ли модель и
  -- умеет ли она вызывать инструменты. Последнее решающее: без вызова
  -- инструментов разбор невозможен в принципе.
  checked_at    TIMESTAMPTZ,
  check_result  JSONB,

  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO prometheus_settings (id) SELECT 1
  WHERE NOT EXISTS (SELECT 1 FROM prometheus_settings);
