-- Поднимаем лимит ответа ИИ-ассистента: 8000 не хватало.
--
-- max_tokens на Opus 4.8 ограничивает МЫШЛЕНИЕ И ТЕКСТ вместе, а мышление там
-- включено (thinking: adaptive) и по умолчанию не отображается — то есть
-- расходует бюджет незаметно. На длинной переписке JSON-ответ обрывался на
-- середине, и ассистент отдавал тикет человеку с «Ответ модели не разобрался
-- как JSON». Документация рекомендует ~16000 для непотокового запроса.
--
-- Трогаем только тех, кто остался на прежнем значении по умолчанию: если
-- админ поднял лимит осознанно, его выбор не перетираем.
UPDATE ai_assistant_settings
   SET max_tokens = 16000
 WHERE max_tokens IS NULL OR max_tokens <= 8000;

ALTER TABLE ai_assistant_settings
  ALTER COLUMN max_tokens SET DEFAULT 16000;
