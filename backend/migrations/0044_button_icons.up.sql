-- Можно ли слать иконки на кнопках меню (Bot API 9.4, icon_custom_emoji_id).
--
-- Иконки работают только если у владельца бота активен Telegram Premium либо
-- боту куплены юзернеймы на Fragment. Узнать это заранее нельзя: getMe такого
-- не отдаёт, а документация лишь называет условие. Остаётся выяснять по факту —
-- и запоминать, чтобы не упираться в один и тот же отказ при каждой отправке.
--
-- NULL — ещё не проверяли, пробуем слать.
-- true  — проверено, иконки принимаются.
-- false — Telegram отказал; шлём без иконок, подписи с эмодзи остаются как есть.
ALTER TABLE telegram_settings
  ADD COLUMN IF NOT EXISTS button_icons_ok BOOLEAN;
